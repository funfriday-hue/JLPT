const expectedCounts = {"vocabulary": 21, "grammar-reading": 22, "listening": 24};
for (let setIndex = 0; setIndex < SET_COUNT; setIndex += 1) {
  const questions = questionsBySet[setIndex];
  if (questions.length !== 67) {
    throw new Error(`Set ${setIndex + 1} has ${questions.length} questions; expected 67.`);
  }
  for (const [section, expected] of Object.entries(expectedCounts)) {
    const actual = questions.filter((question) => question.section === section).length;
    if (actual !== expected) {
      throw new Error(`Set ${setIndex + 1} ${section} count is ${actual}; expected ${expected}.`);
    }
  }
  const lessons = new Set(questions.map((question) => question.lesson));
  for (let lesson = 1; lesson <= 25; lesson += 1) {
    if (!lessons.has(lesson)) {
      throw new Error(`Set ${setIndex + 1} does not cover lesson ${lesson}.`);
    }
  }
  for (const question of questions) {
    if (question.options.length !== 4) {
      throw new Error(`Every question must have four options: ${question.prompt}`);
    }
    if (question.section === "listening" && !question.audioText) {
      throw new Error(`Listening question has no audio text: ${question.prompt}`);
    }
  }
}

// Rotate answer choices after the first six compatibility rows. This keeps the
// answer key balanced without changing the six questions re-seeded at startup.
questionsBySet.forEach((questions, setIndex) => {
  questions.forEach((question, questionIndex) => {
    if (questionIndex < 6) return;
    const offset = (setIndex * 2 + questionIndex) % question.options.length;
    if (offset === 0) return;
    question.options = [...question.options.slice(offset), ...question.options.slice(0, offset)];
    question.answer = (question.answer - offset + question.options.length) % question.options.length;
  });
});

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function rowsInChunks(rows, size = 50) {
  const chunks = [];
  for (let index = 0; index < rows.length; index += size) chunks.push(rows.slice(index, index + size));
  return chunks;
}

