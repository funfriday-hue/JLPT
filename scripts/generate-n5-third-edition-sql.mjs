const questionsBySet = Array.from({length: SET_COUNT}, () => []);

function add(setIndex, section, lesson, type, prompt, promptEn, options, answer, explanation, audioText = null) {
  if (!Number.isInteger(answer) || answer < 0 || answer >= options.length) {
    throw new Error(`Invalid answer index for set ${setIndex + 1}: ${prompt}`);
  }
  questionsBySet[setIndex].push({
    section,
    lesson,
    type,
    prompt,
    promptEn,
    options,
    answer,
    explanation: `第（だい）${lesson}課（か）・${type}: ${explanation}`,
    audioText,
  });
}

// Keep the original six IDs/positions in Sets 1–3 compatible with the app's
// startup seed. This prevents a duplicate (set_id, order_no) after deployment.
for (let setIndex = 0; setIndex < 3; setIndex += 1) {
  const starter = seedQuestions.filter((question) => question.setId === `n5-set-${setIndex + 1}`);
  const lessons = setIndex === 0 ? [4, 3, 6, 5, 4, 6] : setIndex === 1 ? [5, 8, 10, 9, 5, 4] : [14, 6, 13, 12, 17, 7];
  starter.forEach((question, index) => {
    add(
      setIndex,
      question.section,
      lessons[index],
      index < 2 ? "文脈語彙（ぶんみゃくごい）" : index < 4 ? "文法形式（ぶんぽうけいしき）" : index === 4 ? "課題理解（かだいりかい）" : "要点理解（ようてんりかい）",
      question.prompt,
      question.promptEn,
      question.options,
      question.answer,
      question.explanation,
      question.audioText,
    );
  });
}

